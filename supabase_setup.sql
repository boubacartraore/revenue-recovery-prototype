create table if not exists public.reviewer_feedback (
    id bigint generated by default as identity primary key,
    reviewer_id uuid not null,
    submitted_at timestamptz not null,
    name_or_company text,
    role text not null,
    industry text not null,
    years_experience text not null,
    confidence text not null,
    opportunity_id text not null,
    opportunity_type text not null,
    model_rank integer not null check (model_rank between 1 and 8),
    judgment text not null check (judgment in ('About right','Too high','Too low')),
    preferred_rank integer not null check (preferred_rank between 1 and 8),
    rank_difference integer not null,
    notes text,
    general_missing_variables text,
    prototype_version text not null
);

alter table public.reviewer_feedback enable row level security;

-- For this prototype, inserts come from the Streamlit server using the secret key.
-- Do not expose the secret key in app code or GitHub.
